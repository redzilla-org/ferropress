// Compute stack: one Lambda per row of architecture section 3, each with its own role holding
// only the resource-level statements that row lists, plus the triggers that drive them.
import * as path from 'node:path';
import { Duration, RemovalPolicy, Stack, StackProps, Tags } from 'aws-cdk-lib';
import * as events from 'aws-cdk-lib/aws-events';
import * as eventsTargets from 'aws-cdk-lib/aws-events-targets';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as lambda from 'aws-cdk-lib/aws-lambda';
import * as logs from 'aws-cdk-lib/aws-logs';
import * as scheduler from 'aws-cdk-lib/aws-scheduler';
import * as schedulerTargets from 'aws-cdk-lib/aws-scheduler-targets';
import * as secretsmanager from 'aws-cdk-lib/aws-secretsmanager';
import * as sqs from 'aws-cdk-lib/aws-sqs';
import { Construct } from 'constructs';
import { SiteConfig } from './config';
import { DataStack, SITE_PREFIX } from './data-stack';
import { binaryName, FUNCTIONS, FunctionName, UrlFunctionName } from './functions';

export interface ComputeStackProps extends StackProps {
  readonly config: SiteConfig;
  readonly data: DataStack;
}

/** SSM parameter the Edge stack writes with the distribution id `project` invalidates. */
export function distributionParameterName(config: SiteConfig): string {
  return `/ferropress/${config.site}/${config.envName}/distribution-id`;
}

// An on-failure destination that only records the queue ARN; the matching sqs:SendMessage
// statement is added explicitly so the role carries no extra queue actions.
class QueueDestination implements lambda.IDestination {
  constructor(private readonly queue: sqs.IQueue) {}

  bind(): lambda.DestinationConfig {
    return { destination: this.queue.queueArn };
  }
}

export class ComputeStack extends Stack {
  public readonly functions: Record<FunctionName, lambda.Function>;
  public readonly urls: Record<UrlFunctionName, lambda.FunctionUrl>;
  public readonly failureQueue: sqs.Queue;
  public readonly secret: secretsmanager.Secret;

  constructor(scope: Construct, id: string, props: ComputeStackProps) {
    super(scope, id, props);
    const { config, data } = props;
    Tags.of(this).add('ferropress:site', config.site);
    Tags.of(this).add('ferropress:env', config.envName);

    // Salts and keys for nonces and cookies: generated by Secrets Manager, read at init by
    // the functions that need them, never placed in environment variables (section 7).
    this.secret = new secretsmanager.Secret(this, 'SiteSecret', {
      description: 'Ferropress site salts and keys',
      generateSecretString: { passwordLength: 64, excludePunctuation: true },
      removalPolicy: RemovalPolicy.RETAIN,
    });

    // Async invocations that exhaust their retries land here; an alarm watches its depth.
    this.failureQueue = new sqs.Queue(this, 'FailureQueue', {
      retentionPeriod: Duration.days(14),
      enforceSSL: true,
    });

    // Resource ARNs the statements below scope to.
    const objects = (prefix: string) => data.bucket.arnForObjects(`${SITE_PREFIX}${prefix}/*`);
    const clusterArn = data.cluster.attrResourceArn;
    const mailIdentityArn = this.formatArn({
      service: 'ses',
      resource: 'identity',
      resourceName: config.mailIdentity,
    });
    const distributionParameterArn = this.formatArn({
      service: 'ssm',
      resource: 'parameter',
      resourceName: distributionParameterName(config).slice(1),
    });

    const fns = {} as Record<FunctionName, lambda.Function>;
    // `project` is created first because every write path holds a statement on it.
    const ordered = [...FUNCTIONS].sort((a, b) => Number(b.name === 'project') - Number(a.name === 'project'));
    for (const spec of ordered) {
      const project = fns.project as lambda.Function | undefined;
      const allow = (actions: string[], resources: string[]) =>
        new iam.PolicyStatement({ actions, resources });
      const dbConnect = allow(['dsql:DbConnect'], [clusterArn]);
      const nudge = () => allow(['lambda:InvokeFunction'], [requireProject(project).functionArn]);
      const secret = allow(['secretsmanager:GetSecretValue'], [this.secret.secretArn]);
      const sessionsRead = allow(['dynamodb:GetItem'], [data.sessionsTable.tableArn]);
      const limitsUpdate = allow(['dynamodb:UpdateItem'], [data.limitsTable.tableArn]);

      // The resource-level IAM scope column of section 3, plus the reads and nudges that
      // sections 5, 7 and 9 require of the same function.
      const statements: Record<FunctionName, () => iam.PolicyStatement[]> = {
        read: () => [
          allow(['dynamodb:GetItem'], [data.readTable.tableArn]),
          allow(['s3:GetObject'], [objects('rendered'), objects('fragments')]),
        ],
        admin: () => [dbConnect, sessionsRead, nudge(), secret],
        auth: () => [
          dbConnect,
          allow(['dynamodb:PutItem', 'dynamodb:DeleteItem', 'dynamodb:GetItem'], [data.sessionsTable.tableArn]),
          allow(['dynamodb:Query'], [`${data.sessionsTable.tableArn}/index/user_id`]),
          limitsUpdate,
          allow(['ses:SendEmail'], [mailIdentityArn]),
          secret,
        ],
        'media-sign': () => [allow(['s3:PutObject'], [objects('incoming')]), sessionsRead],
        'media-process': () => [
          allow(['s3:GetObject', 's3:DeleteObject'], [objects('incoming')]),
          allow(['s3:PutObject'], [objects('uploads')]),
          dbConnect,
          nudge(),
        ],
        search: () => [
          allow(['dynamodb:GetItem'], [data.readTable.tableArn]),
          allow(['s3:GetObject'], [objects('search')]),
        ],
        comments: () => [dbConnect, limitsUpdate, nudge(), secret],
        project: () => [
          dbConnect,
          allow(['s3:PutObject'], [objects('rendered'), objects('fragments'), objects('search')]),
          allow(['dynamodb:PutItem', 'dynamodb:DeleteItem', 'dynamodb:Query'], [data.readTable.tableArn]),
          allow(['ssm:GetParameter'], [distributionParameterArn]),
        ],
        cron: () => [dbConnect, nudge()],
        import: () => [
          allow(['s3:GetObject'], [objects('imports')]),
          allow(['s3:PutObject'], [objects('uploads')]),
          dbConnect,
          allow(['dynamodb:GetItem', 'dynamodb:PutItem'], [data.readTable.tableArn]),
          nudge(),
        ],
      };

      // Environment: names and endpoints only, matching what the role may touch.
      const env: Record<string, string> = { FP_SITE: config.site, FP_BASE_PATH: config.basePath };
      const statementList = statements[spec.name]();
      const resources = statementList.flatMap((s) => s.resources);
      const uses = (arn: string) => resources.some((r) => r === arn || r.startsWith(`${arn}/`));
      if (uses(data.readTable.tableArn)) env.FP_READ_TABLE = data.readTable.tableName;
      if (uses(data.sessionsTable.tableArn)) env.FP_SESSIONS_TABLE = data.sessionsTable.tableName;
      if (uses(data.limitsTable.tableArn)) env.FP_LIMITS_TABLE = data.limitsTable.tableName;
      if (statementList.some((s) => s.actions.some((a) => a.startsWith('s3:')))) {
        env.FP_BUCKET = data.bucket.bucketName;
      }
      if (uses(clusterArn)) env.FP_DSQL_ENDPOINT = data.cluster.attrEndpoint;
      if (uses(this.secret.secretArn)) env.FP_SECRET_ARN = this.secret.secretArn;
      if (project !== undefined && uses(project.functionArn)) env.FP_PROJECT_FUNCTION = project.functionName;
      if (uses(mailIdentityArn)) env.FP_MAIL_IDENTITY = config.mailIdentity;
      if (uses(distributionParameterArn)) env.FP_DISTRIBUTION_PARAM = distributionParameterName(config);

      // Thirty-day retention (section 10); the role may write only to this group.
      const logGroup = new logs.LogGroup(this, `${pascal(spec.name)}Logs`, {
        retention: logs.RetentionDays.ONE_MONTH,
        removalPolicy: RemovalPolicy.DESTROY,
      });
      const role = new iam.Role(this, `${pascal(spec.name)}Role`, {
        assumedBy: new iam.ServicePrincipal('lambda.amazonaws.com'),
        description: `Ferropress ${spec.name} function`,
      });
      role.addToPolicy(allow(['logs:CreateLogStream', 'logs:PutLogEvents'], [logGroup.logGroupArn]));
      for (const statement of statementList) {
        role.addToPolicy(statement);
      }
      if (spec.async) {
        role.addToPolicy(allow(['sqs:SendMessage'], [this.failureQueue.queueArn]));
      }

      // Rust binaries for aarch64 musl, built by CI into <assetDir>/<binary>/bootstrap.
      const fn = new lambda.Function(this, `${pascal(spec.name)}Function`, {
        description: `Ferropress ${spec.name}`,
        runtime: lambda.Runtime.PROVIDED_AL2023,
        architecture: lambda.Architecture.ARM_64,
        handler: 'bootstrap',
        code: lambda.Code.fromAsset(path.join(config.assetDir, binaryName(spec.name))),
        memorySize: spec.memoryMb,
        timeout: Duration.seconds(spec.timeoutSeconds),
        role,
        logGroup,
        loggingFormat: lambda.LoggingFormat.JSON,
        environment: env,
        // Projection is serial and ordered (section 5): never two projectors at once.
        reservedConcurrentExecutions: spec.name === 'project' ? 1 : undefined,
        onFailure: spec.async ? new QueueDestination(this.failureQueue) : undefined,
      });
      fns[spec.name] = fn;
    }
    this.functions = fns;

    // Function URLs: IAM-authenticated, reachable only through CloudFront OAC (Edge stack).
    const urls = {} as Record<UrlFunctionName, lambda.FunctionUrl>;
    for (const spec of FUNCTIONS.filter((f) => f.url)) {
      urls[spec.name as UrlFunctionName] = fns[spec.name].addFunctionUrl({
        authType: lambda.FunctionUrlAuthType.AWS_IAM,
      });
    }
    this.urls = urls;

    // Safety-net schedules: the projector drains the outbox every 5 minutes even if a nudge
    // is lost, and cron runs scheduled publishing every minute.
    new scheduler.Schedule(this, 'ProjectSchedule', {
      schedule: scheduler.ScheduleExpression.rate(Duration.minutes(5)),
      target: new schedulerTargets.LambdaInvoke(fns.project, { retryAttempts: 0 }),
      description: 'Drain the Ferropress outbox',
    });
    new scheduler.Schedule(this, 'CronSchedule', {
      schedule: scheduler.ScheduleExpression.rate(Duration.minutes(1)),
      target: new schedulerTargets.LambdaInvoke(fns.cron, { retryAttempts: 0 }),
      description: 'Run Ferropress scheduled events',
    });

    // Object-created events from the upload landing areas, delivered by EventBridge.
    const objectCreated = (id: string, prefix: string, target: lambda.IFunction) =>
      new events.Rule(this, id, {
        eventPattern: {
          source: ['aws.s3'],
          detailType: ['Object Created'],
          detail: {
            bucket: { name: [data.bucket.bucketName] },
            object: { key: [{ prefix: `${SITE_PREFIX}${prefix}/` }] },
          },
        },
        targets: [new eventsTargets.LambdaFunction(target)],
      });
    objectCreated('IncomingCreated', 'incoming', fns['media-process']);
    objectCreated('ImportsCreated', 'imports', fns.import);
  }
}

// The nudge statement is built only after `project` exists; the sort above guarantees that.
function requireProject(project: lambda.Function | undefined): lambda.Function {
  if (project === undefined) {
    throw new Error('project function must be created before the functions that nudge it');
  }
  return project;
}

function pascal(name: string): string {
  return name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}
