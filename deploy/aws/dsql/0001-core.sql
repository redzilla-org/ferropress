-- Aurora DSQL schema for one site (table prefix fp_), serverless profile.
-- Design: docs/aws/architecture.md section 4; tracking issue #2.
--
-- Reference tables are rendered from contracts/inventory/tables.jsonl (single-site scope) so the
-- column names, order, defaults and indexes stay the recorded facts. Choices DSQL forces:
-- * Every identifier is double-quoted so mixed-case reference names ("ID", "comment_ID") come back
--   unchanged in result sets and the existing row parsers keep working.
-- * auto_increment -> identity with CACHE 1: DSQL accepts only CACHE 1 or >= 65536, and CACHE 1
--   keeps ids sequential like the reference's auto-increment. BY DEFAULT lets imports keep ids.
-- * datetime -> varchar(19): the reference stores the zero date 0000-00-00 00:00:00, which
--   timestamp cannot hold; the fixed-width text still sorts chronologically.
-- * tinytext -> varchar(255); text/mediumtext/longtext -> text (1 MiB after compression in DSQL).
-- * bigint unsigned -> bigint: DSQL has no unsigned types; ids stay far below 2^63.
-- * No foreign keys: the reference has none, and plugins rely on deleting rows without cascades.
-- * MySQL index prefix lengths such as meta_key(191) are dropped; DSQL index keys allow 1 KiB.
-- * Indexes are CREATE INDEX ASYNC, the DSQL form for non-blocking builds.
--
-- The migration runner executes each statement (terminated by ";" at end of line) in its own
-- transaction, because DSQL allows one DDL statement per transaction and no DDL/DML mixing.

-- Applied migrations, so the runner is idempotent across deploys.
CREATE TABLE "fp_schema_migrations" (
    "version" varchar(64) NOT NULL,
    "statement" integer NOT NULL,
    "applied_at" timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY ("version", "statement")
);

-- Outbox: written in the same transaction as every content change so the projector job can
-- update DynamoDB and S3 at least once without dual writes. uuid keys spread inserts across
-- DSQL partitions instead of creating a hot tail.
CREATE TABLE "fp_outbox" (
    "id" uuid NOT NULL DEFAULT gen_random_uuid(),
    "created_at" timestamptz NOT NULL DEFAULT now(),
    "aggregate" varchar(32) NOT NULL,
    "aggregate_id" bigint NOT NULL,
    "change" varchar(32) NOT NULL,
    "payload" jsonb NOT NULL DEFAULT '{}',
    PRIMARY KEY ("id")
);
-- The projector drains in creation order.
CREATE INDEX ASYNC "fp_outbox_created_at" ON "fp_outbox" ("created_at");

-- Reference tables follow.

CREATE TABLE "fp_commentmeta" (
    "meta_id" bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
    "comment_id" bigint NOT NULL DEFAULT 0,
    "meta_key" varchar(255),
    "meta_value" text,
    PRIMARY KEY ("meta_id")
);
CREATE INDEX ASYNC "fp_commentmeta_comment_id" ON "fp_commentmeta" ("comment_id");
CREATE INDEX ASYNC "fp_commentmeta_meta_key" ON "fp_commentmeta" ("meta_key");

CREATE TABLE "fp_comments" (
    "comment_ID" bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
    "comment_post_ID" bigint NOT NULL DEFAULT 0,
    "comment_author" varchar(255) NOT NULL,
    "comment_author_email" varchar(100) NOT NULL DEFAULT '',
    "comment_author_url" varchar(200) NOT NULL DEFAULT '',
    "comment_author_IP" varchar(100) NOT NULL DEFAULT '',
    "comment_date" varchar(19) NOT NULL DEFAULT '0000-00-00 00:00:00',
    "comment_date_gmt" varchar(19) NOT NULL DEFAULT '0000-00-00 00:00:00',
    "comment_content" text NOT NULL,
    "comment_karma" integer NOT NULL DEFAULT 0,
    "comment_approved" varchar(20) NOT NULL DEFAULT '1',
    "comment_agent" varchar(255) NOT NULL DEFAULT '',
    "comment_type" varchar(20) NOT NULL DEFAULT 'comment',
    "comment_parent" bigint NOT NULL DEFAULT 0,
    "user_id" bigint NOT NULL DEFAULT 0,
    PRIMARY KEY ("comment_ID")
);
CREATE INDEX ASYNC "fp_comments_comment_post_ID" ON "fp_comments" ("comment_post_ID");
CREATE INDEX ASYNC "fp_comments_comment_approved_date_gmt" ON "fp_comments" ("comment_approved", "comment_date_gmt");
CREATE INDEX ASYNC "fp_comments_comment_date_gmt" ON "fp_comments" ("comment_date_gmt");
CREATE INDEX ASYNC "fp_comments_comment_parent" ON "fp_comments" ("comment_parent");
CREATE INDEX ASYNC "fp_comments_comment_author_email" ON "fp_comments" ("comment_author_email");

CREATE TABLE "fp_links" (
    "link_id" bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
    "link_url" varchar(255) NOT NULL DEFAULT '',
    "link_name" varchar(255) NOT NULL DEFAULT '',
